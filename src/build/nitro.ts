import { mkdirSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import type { StorageConfig } from "../config";
import { parseDuration } from "../runtime/util";
import { detectAdapters } from "./adapters";
import { distEntry, loadProject, type LoadedProject } from "./load";

/** Presets that run as one long-lived process, where a local filesystem and timers are durable enough. */
const SERVER_PRESETS = /^(node|node-server|node-cluster|node-middleware|bun|deno-server)$/;

/** Default time budget per invocation, under each platform's limit for work after the response. */
const PRESET_BUDGETS: [RegExp, string][] = [
  [/^cloudflare/, "25s"],
  [/^vercel/, "240s"],
  [/^netlify/, "20s"],
  [/^aws-(lambda|amplify)/, "25s"],
  [/^azure/, "200s"],
  [/^deno-deploy/, "50s"],
];

export const DEFAULT_STORAGE: StorageConfig = { driver: "fs-lite", base: ".data/agent-unit" };

export function resolvePreset(project: LoadedProject, preset?: string): string {
  return preset ?? project.config.preset ?? process.env.NITRO_PRESET ?? "node-server";
}

export function resolveBudget(project: LoadedProject, preset: string): number | undefined {
  const budget = project.config.budget;
  if (budget === false) return undefined;
  if (budget !== undefined) return parseDuration(budget);
  const match = PRESET_BUDGETS.find(([pattern]) => pattern.test(preset));
  return match ? parseDuration(match[1]) : undefined;
}

export function resolveStorage(project: LoadedProject, preset: string, warn: (message: string) => void): StorageConfig {
  if (project.config.storage) return project.config.storage;
  if (SERVER_PRESETS.test(preset)) return DEFAULT_STORAGE;
  warn(
    `The "${preset}" preset has no durable local disk, so runs would be lost between invocations. ` +
      `Set \`storage\` in agent-unit.config.ts to a shared driver (redis, upstash, cloudflare-kv-binding, vercel-kv, netlify-blobs, ...). Using memory for now.`,
  );
  return { driver: "memory" };
}

const toImport = (from: string, file: string) => {
  const path = relative(from, file).replaceAll("\\", "/");
  return JSON.stringify(path.startsWith(".") ? path : `./${path}`);
};

/** Writes the Nitro server entry, the shared runtime module and the sweep task into `dir`. */
export function generateEntry(project: LoadedProject, dir: string, options: { budgetMs?: number }) {
  mkdirSync(dir, { recursive: true });
  const adapters = detectAdapters(project.root);
  const imports = [
    `import { createAgentUnit } from ${JSON.stringify(distEntry("server"))};`,
    `import { useStorage } from "nitro/storage";`,
    ...adapters.map((adapter) => `import { ${adapter.exportName} } from ${JSON.stringify(distEntry(adapter.entry))};`),
  ];
  imports.push(project.configFile ? `import config from ${toImport(dir, project.configFile)};` : `const config = {};`);
  const agentEntries = Object.entries(project.agentFiles).map(([name, file], index) => {
    imports.push(`import * as agent$${index} from ${toImport(dir, file)};`);
    return `  ${JSON.stringify(name)}: agent$${index},`;
  });

  writeFileSync(
    join(dir, "runtime.mjs"),
    `// Generated by agent-unit. Do not edit.
${imports.join("\n")}

// Secrets come from Workers bindings when present, otherwise from the process environment.
const env = new Proxy({}, {
  get: (_, key) => typeof key === "string" ? (globalThis.__env__?.[key] ?? globalThis.process?.env?.[key]) : undefined,
});

export const unit = createAgentUnit({
  name: config.name ?? ${JSON.stringify(project.name)},
  agents: config.agents ?? {
${agentEntries.join("\n")}
  },
  adapters: [...(config.adapters ?? []), ${adapters.map((adapter) => adapter.exportName).join(", ")}],
  storage: useStorage("agent-unit"),
  budget: ${options.budgetMs ?? "false"},
  basePath: config.basePath,
  authorize: config.authorize,
  env,
});
`,
  );

  writeFileSync(
    join(dir, "entry.mjs"),
    `// Generated by agent-unit. Do not edit.
import { defineHandler } from "nitro";
import { unit } from "./runtime.mjs";

export default defineHandler((event) =>
  unit.handler(event.req, { waitUntil: (promise) => event.waitUntil(promise) }),
);
`,
  );

  writeFileSync(
    join(dir, "sweep.mjs"),
    `// Generated by agent-unit. Do not edit.
import { defineTask } from "nitro/task";
import { unit } from "./runtime.mjs";

export default defineTask({
  meta: { description: "Wake due agent-unit runs and recover stalled ones." },
  async run() {
    const { woken, recovered, settled } = await unit.engine.sweep();
    await settled;
    return { result: { woken, recovered } };
  },
});
`,
  );
  return { adapters: adapters.map((adapter) => adapter.package) };
}

export interface BuildOptions {
  root?: string;
  preset?: string;
  /** Output directory. Default `.output`. */
  outDir?: string;
  minify?: boolean;
  logger?: { info(message: string): void; warn(message: string): void };
}

export interface BuildResult {
  preset: string;
  outDir: string;
  agents: string[];
  adapters: string[];
  budgetMs?: number;
  storage: StorageConfig;
}

/** Builds the app's agents into a deployable Nitro server for the chosen preset. */
export async function build(options: BuildOptions = {}): Promise<BuildResult> {
  const logger = options.logger ?? { info: console.log, warn: console.warn };
  const project = await loadProject(options.root);
  const preset = resolvePreset(project, options.preset);
  const budgetMs = resolveBudget(project, preset);
  const storage = resolveStorage(project, preset, logger.warn);
  const genDir = join(project.root, ".agent-unit");
  const { adapters } = generateEntry(project, genDir, { budgetMs });
  const outDir = resolve(project.root, options.outDir ?? ".output");

  const tasks: Record<string, unknown> = {};
  const scheduledTasks: Record<string, string> = {};
  if (project.config.sweep !== false) {
    tasks["agent-unit:sweep"] = { handler: join(genDir, "sweep.mjs"), description: "Wake due runs and recover stalled ones." };
    scheduledTasks[project.config.sweep ?? "* * * * *"] = "agent-unit:sweep";
  }

  const { createNitro, prepare, copyPublicAssets, build: buildNitro } = await import("nitro/builder");
  const userNitro = project.config.nitro ?? {};
  const nitro = await createNitro({
    rootDir: project.root,
    dev: false,
    preset,
    builder: "rolldown",
    compatibilityDate: "2025-07-01",
    minify: options.minify ?? false,
    buildDir: join(genDir, "nitro"),
    output: { dir: outDir },
    serverEntry: { handler: join(genDir, "entry.mjs"), format: "web" },
    storage: { "agent-unit": storage },
    experimental: { tasks: Object.keys(tasks).length > 0 },
    tasks,
    scheduledTasks,
    logLevel: 1,
    ...userNitro,
  } as never);
  try {
    await prepare(nitro);
    await copyPublicAssets(nitro);
    await buildNitro(nitro);
  } finally {
    await nitro.close();
  }

  const agents = project.config.agents ? Object.keys(project.config.agents) : Object.keys(project.agentFiles);
  logger.info(`agent-unit: built ${agents.length} agent(s) for ${preset} into ${relative(process.cwd(), outDir) || "."}`);
  return { preset, outDir, agents, adapters, budgetMs, storage };
}
