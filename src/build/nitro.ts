import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import type { StorageConfig } from "../config";
import { loadProject, resolveServer, toImport } from "./load";
import { prepareTasks } from "./tasks";

// The compiler: one Nitro build of the app's server for any preset. The server is the app's own
// (`server` in agent-unit.config.ts) or, without one, agent-unit's engine from ./engine.

export function resolvePreset(project: { config: { preset?: string } }, preset?: string): string {
  return preset ?? project.config.preset ?? process.env.NITRO_PRESET ?? "node-server";
}

/**
 * The Nitro entry for the app's own server: a module whose default export handles web requests,
 * either a function `(request, env, ctx) => Response` or an object with that `fetch` method (a Hono
 * app, `export default { fetch }`). On Workers it gets the Worker's `env` and `ctx`, elsewhere a
 * `ctx` whose `waitUntil` is agent-unit's (see `agent-unit/env`).
 */
function writeServerEntry(file: string, label: string, genDir: string): string {
  mkdirSync(genDir, { recursive: true });
  const entry = join(genDir, "server.mjs");
  writeFileSync(
    entry,
    `// Generated by agent-unit. Do not edit.
import { defineHandler } from "nitro";
import { runInScope, waitUntil } from "agent-unit/env";
import app from ${toImport(genDir, file)};

const handle = typeof app === "function" ? app : typeof app?.fetch === "function" ? app.fetch.bind(app) : undefined;
if (!handle) throw new Error(${JSON.stringify(`agent-unit: ${label} must export default a fetch handler: a function (request) => Response, or an object with a fetch method (a Hono app, { fetch }).`)});

export default defineHandler((event) => {
  const cloudflare = event.req.runtime?.cloudflare;
  // The host's waitUntil where it has one; without it, work handed to waitUntil finishes before the response.
  const host = typeof event.req.waitUntil === "function" ? (promise) => event.req.waitUntil(promise) : undefined;
  const ctx = cloudflare?.context ?? { waitUntil, passThroughOnException() {} };
  return runInScope(host, () => handle(event.req, cloudflare?.env, ctx));
});
`,
  );
  return entry;
}

interface CloudflareOptions {
  exports?: string;
  wrangler?: Record<string, unknown>;
  [key: string]: unknown;
}

/**
 * Workers settings: a compatibility date recent enough for the Node APIs agent SDKs reach for
 * (the AI SDK's gateway reads files through `node:fs`), and in the Durable Objects runtime the
 * exported classes, their bindings and their migration. The app's own `nitro.cloudflare` is merged over.
 */
const WS_SHIM = `// Generated by agent-unit: Workers' built-in WebSocket in place of the Node \`ws\` package.
const unavailable = (name) =>
  function () {
    throw new Error(\`ws.\${name} is not available on Cloudflare Workers.\`);
  };
const WebSocket = globalThis.WebSocket;
export default WebSocket;
export { WebSocket };
export const WebSocketServer = unavailable("WebSocketServer");
export const createWebSocketStream = unavailable("createWebSocketStream");
`;

function cloudflareConfig(root: string, genDir: string, durable: boolean, user: CloudflareOptions = {}): CloudflareOptions {
  const wrangler: Record<string, unknown> = { compatibility_date: "2025-09-15" };
  // Framework SDKs import Node modules at load that Workers only provide (as stubs) from compatibility
  // date 2026 on, or with these flags: Mastra imports child_process, readline and worker_threads, the
  // OpenAI Agents SDK imports tty (through \`debug\`). One missing module stops the whole Worker from
  // starting, every agent with it. Stubs cost nothing unless imported, and dependencies move between
  // versions, so every Worker gets them.
  const flags = [
    "enable_nodejs_child_process_module",
    "enable_nodejs_readline_module",
    "enable_nodejs_worker_threads_module",
    "enable_nodejs_tty_module",
  ];
  const own = user.wrangler ?? {};
  const objects: { name: string; class_name: string }[] = [];
  const migrations: { tag: string }[] = [];
  let exports = user.exports;
  if (durable) {
    objects.push({ name: "AGENT_UNIT_RUNS", class_name: "AgentUnitRun" }, { name: "AGENT_UNIT_INDEX", class_name: "AgentUnitIndex" });
    migrations.push({ tag: "agent-unit-v1", new_sqlite_classes: ["AgentUnitRun", "AgentUnitIndex"] } as { tag: string });
    // Nitro takes one exports file, and the durable runtime needs its own: the app's classes (a
    // storage provider's Durable Object, a Workflow) are exported beside agent-unit's, not instead.
    const appExports = user.exports ? resolve(root, user.exports) : NITRO_EXPORTS.map((name) => join(root, name)).find(existsSync);
    if (appExports && !existsSync(appExports)) throw new Error(`agent-unit: the Cloudflare exports file "${user.exports}" does not exist.`);
    exports = join(genDir, "exports.mjs");
    writeFileSync(
      exports,
      `// Generated by agent-unit. Do not edit.\nexport * from ${toImport(genDir, join(genDir, "durable.mjs"))};\n${appExports ? `export * from ${toImport(genDir, appExports)};\n` : ""}`,
    );
  }
  // The app's Durable Objects and migrations are added to agent-unit's, never in place of them.
  const appObjects = ((own.durable_objects as { bindings?: { name: string; class_name: string }[] } | undefined)?.bindings ?? []);
  const appMigrations = (own.migrations as { tag: string }[] | undefined) ?? [];
  for (const binding of appObjects) {
    if (objects.some((reserved) => reserved.name === binding.name || reserved.class_name === binding.class_name)) {
      throw new Error(`agent-unit: the Durable Object binding "${binding.name}" (${binding.class_name}) is reserved by agent-unit; use another name.`);
    }
  }
  if (appMigrations.some((migration) => migrations.some((reserved) => reserved.tag === migration.tag))) {
    throw new Error(`agent-unit: the migration tag "agent-unit-v1" is reserved by agent-unit; use another tag.`);
  }
  const allObjects = [...objects, ...appObjects];
  const allMigrations = [...migrations, ...appMigrations];
  return {
    ...user,
    ...(exports ? { exports } : {}),
    wrangler: {
      ...wrangler,
      ...own,
      ...(allObjects.length ? { durable_objects: { ...(own.durable_objects as object | undefined), bindings: allObjects } } : {}),
      ...(allMigrations.length ? { migrations: allMigrations } : {}),
      compatibility_flags: [...new Set([...flags, ...((own.compatibility_flags as string[] | undefined) ?? [])])],
    },
  };
}

/** Files Nitro picks up on its own as the Worker's extra exports, when `cloudflare.exports` is not set. */
const NITRO_EXPORTS = ["exports.cloudflare.ts", "exports.cloudflare.mts", "exports.cloudflare.js", "exports.cloudflare.mjs"];

export interface BuildOptions {
  root?: string;
  preset?: string;
  /** Output directory. Default: the preset's own (`.output`, `.vercel/output`, ...). */
  outDir?: string;
  minify?: boolean;
  logger?: { info(message: string): void; warn(message: string): void };
}

export interface BuildResult {
  preset: string;
  /** `"none"` when the app brings its own `server`. */
  runtime: "default" | "durable-objects" | "none";
  outDir: string;
  /** The app's own server file, when it has one. */
  server?: string;
  agents: string[];
  adapters: string[];
  budgetMs?: number;
  /** Run storage, when agent-unit's engine is the server. */
  storage?: StorageConfig;
}

/** Builds the app's server (its own, or agent-unit's engine serving its agents) for the chosen preset. */
export async function build(options: BuildOptions = {}): Promise<BuildResult> {
  const logger = options.logger ?? { info: console.log, warn: console.warn };
  const project = await loadProject(options.root);
  const preset = resolvePreset(project, options.preset);
  const genDir = join(project.root, ".agent-unit");
  // The engine is imported only when it is the server, so an app's own server builds without it.
  const own = project.config.server ? await resolveServer(project, genDir, preset) : undefined;
  const engine = own ? undefined : (await import("./engine")).prepareEngine(project, preset, genDir, logger.warn);
  const entry = own ? writeServerEntry(own.file, own.label, genDir) : engine!.entry;
  const server = own?.label;
  const durable = engine?.runtime === "durable-objects";
  // The app's own tasks run beside the engine's sweep, on the same Nitro scheduler.
  const appTasks = prepareTasks(project, genDir, preset, logger.warn);
  const engineNitro = (engine?.nitro ?? {}) as { tasks?: Record<string, unknown>; scheduledTasks?: Record<string, string | string[]> };
  const tasks = { ...engineNitro.tasks, ...appTasks.tasks };
  const scheduledTasks: Record<string, string[]> = {};
  for (const source of [engineNitro.scheduledTasks ?? {}, appTasks.scheduledTasks]) {
    for (const [cron, names] of Object.entries(source)) (scheduledTasks[cron] ??= []).push(...[names].flat());
  }

  const { createNitro, prepare, copyPublicAssets, build: buildNitro } = await import("nitro/builder");
  const { cloudflare: nitroCloudflare, ...userNitro } = project.config.nitro ?? {};
  // `cloudflare` and the older `nitro.cloudflare` are the same settings; both apply.
  const fromNitro = (nitroCloudflare ?? {}) as CloudflareOptions;
  const fromConfig = project.config.cloudflare ?? {};
  const userCloudflare: CloudflareOptions = {
    ...fromNitro,
    ...fromConfig,
    wrangler: { ...(fromNitro.wrangler as object | undefined), ...fromConfig.wrangler },
  } as CloudflareOptions;
  const cloudflare = /^cloudflare/.test(preset);
  const alias: Record<string, string> = {};
  if (cloudflare) {
    // The Node \`ws\` package (Mastra imports it) cannot run on Workers, and loading it crashes the
    // Worker at startup; Workers have a WebSocket client built in.
    mkdirSync(genDir, { recursive: true });
    alias.ws = join(genDir, "ws.mjs");
    writeFileSync(alias.ws, WS_SHIM);
  }
  const nitro = await createNitro({
    rootDir: project.root,
    dev: false,
    preset,
    builder: "rolldown",
    compatibilityDate: "2025-07-01",
    minify: options.minify ?? false,
    buildDir: join(genDir, "nitro"),
    ...(options.outDir ? { output: { dir: resolve(project.root, options.outDir) } } : {}),
    serverEntry: { handler: entry, format: "web" },
    ...engine?.nitro,
    experimental: { tasks: Object.keys(tasks).length > 0 },
    tasks,
    scheduledTasks,
    ...(cloudflare ? { cloudflare: cloudflareConfig(project.root, genDir, durable, userCloudflare) } : {}),
    logLevel: 1,
    ...userNitro,
    alias: { ...alias, ...(userNitro as { alias?: Record<string, string> }).alias },
  } as never);
  const outDir = nitro.options.output.dir;
  // Some presets (Netlify, Stormkit) put static files beside the project, in \`<root>/dist\`. With an
  // explicit output directory everything stays inside it, so builds for several presets can sit
  // side by side (\`dist/node\`, \`dist/netlify\`, ...) without one cleaning another away.
  if (options.outDir && relative(outDir, nitro.options.output.publicDir).startsWith("..")) {
    nitro.options.output.publicDir = join(outDir, "public");
  }
  try {
    await prepare(nitro);
    await copyPublicAssets(nitro);
    await buildNitro(nitro);
  } finally {
    await nitro.close();
  }
  await engine?.finish({ outDir, serverDir: nitro.options.output.serverDir }, logger.warn);

  const where = relative(process.cwd(), outDir) || ".";
  if (!engine) {
    logger.info(`agent-unit: built ${server} for ${preset} into ${where}`);
    return { preset, runtime: "none", outDir, server, agents: [], adapters: [] };
  }
  logger.info(`agent-unit: built ${engine.agents.length} agent(s) for ${preset} into ${where}`);
  return { preset, runtime: engine.runtime, outDir, agents: engine.agents, adapters: engine.adapters, budgetMs: engine.budgetMs, storage: engine.storage };
}
