import { existsSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import type { ServerPreset } from "../config";
import { MASTRA_ENTRIES, toImport } from "../build/load";

export interface MastraPresetOptions {
  /** The module that creates your Mastra instance. Default: `src/mastra/index.ts`, where Mastra's CLI puts it. */
  entry?: string;
  /** The export holding the instance. Default `mastra`, then the default export. */
  export?: string;
}

/** Whether `pkg` is installed for the app at `root`, looking up the directories as Node does. */
function installed(root: string, pkg: string): boolean {
  for (let dir = root; ; dir = dirname(dir)) {
    if (existsSync(join(dir, "node_modules", pkg, "package.json"))) return true;
    if (dirname(dir) === dir) return false;
  }
}

/**
 * Builds Mastra's own server: its routes, auth, memory and workflows, on the storage your Mastra
 * instance configures, served through Mastra's Hono adapter (`@mastra/hono`). agent-unit adds none
 * of its engine; it only builds the server for the host.
 *
 * ```ts
 * // agent-unit.config.ts
 * import { defineConfig } from "agent-unit";
 * import { mastra } from "agent-unit/presets/mastra";
 *
 * export default defineConfig({ server: mastra() });
 * ```
 */
export function mastra(options: MastraPresetOptions = {}): ServerPreset {
  return {
    name: "mastra",
    entry({ root, genDir }) {
      const file = options.entry ? resolve(root, options.entry) : MASTRA_ENTRIES.map((name) => join(root, name)).find((path) => existsSync(path));
      if (!file || !existsSync(file)) {
        throw new Error(
          `agent-unit: the Mastra preset could not find your Mastra instance (${options.entry ?? MASTRA_ENTRIES[0]}). Pass its file: mastra({ entry: "./path/to/mastra.ts" }).`,
        );
      }
      const missing = ["@mastra/hono", "hono"].filter((pkg) => !installed(root, pkg));
      if (missing.length) {
        throw new Error(`agent-unit: the Mastra preset serves Mastra through its Hono adapter. Install ${missing.join(" and ")}: npm install ${missing.join(" ")}`);
      }
      const name = options.export ?? "mastra";
      const where = relative(root, file).replaceAll("\\", "/");
      const server = join(genDir, "mastra-server.ts");
      writeFileSync(
        server,
        `// Generated by agent-unit's Mastra preset. Do not edit.
// @ts-nocheck
import { Hono } from "hono";
import { MastraServer } from "@mastra/hono";
import * as app from ${toImport(genDir, file)};

// Looked up at run time, so the bundler does not warn about whichever of the two the module lacks.
const mastra = Reflect.get(app, ${JSON.stringify(name)}) ?? Reflect.get(app, "default");
if (!mastra) {
  throw new Error(${JSON.stringify(`agent-unit: ${where} must export your Mastra instance as \`${name}\` (export const ${name} = new Mastra({ ... })).`)});
}

const server = new Hono();
await new MastraServer({ app: server, mastra }).init();

export default server;
`,
      );
      return server;
    },
  };
}

export default mastra;
